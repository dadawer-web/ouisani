package com.ouisani.aios.user.apps.omnifactory;

import com.ouisani.aios.user.sdk.AiosSdk;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * 基类模板管理器 — 向 VFS 注入工业级 Python 基类，降低母体代码生成难度。
 * <p>
 * OS 类比：相当于 Linux 的 vDSO — 内核预置一套高性能的共享库，
 * 用户空间程序无需自己实现底层系统调用，直接链接即可。
 * <p>
 * 母体不再要求 LLM 生成 while True + config 热更 + EventBus 读写等底层代码，
 * 只需继承 BaseAgent 并重写 process_data() 即可。
 */
public class TemplateManager {

    private static final Logger log = LoggerFactory.getLogger(TemplateManager.class);

    private static final String BASE_AGENT_PY = """
            #!/usr/bin/env python3
            # BaseAgent.py — AIOS Industrial-Grade Agent Framework
            # Auto-generated by TemplateManager. DO NOT EDIT.
            #
            # All agent nodes inherit this base class. You only need to override
            # process_data(self, data) to implement your business logic.
            #
            # Features built-in:
            #   - Dynamic config hot-reload from /factory/configs/{node_id}.json
            #   - Race-condition-safe JSON parsing (handles partial writes)
            #   - EventBus read/write via stdin/stdout
            #   - Graceful error handling with auto-recovery
            #   - CPU-friendly sleep for polling tasks

            import json
            import time
            import sys
            import os
            import traceback


            class BaseAgent:
                def __init__(self):
                    self.node_id = os.environ.get('NODE_ID', 'unknown')
                    self.input_topic = os.environ.get('INPUT_TOPIC', '')
                    self.output_topic = os.environ.get('OUTPUT_TOPIC', '')
                    self.config_path = f'/factory/configs/{self.node_id}.json'
                    self.config = {}
                    self._load_config()

                def _load_config(self):
                    try:
                        with open(self.config_path, 'r') as f:
                            new_config = json.load(f)
                            if new_config:
                                self.config = new_config
                    except (FileNotFoundError, json.JSONDecodeError):
                        pass  # File missing or host is writing — keep last config

                def read_input(self):
                    try:
                        line = sys.stdin.readline()
                        if line and line.strip():
                            return json.loads(line.strip())
                    except (json.JSONDecodeError, EOFError):
                        pass
                    return None

                def publish(self, data):
                    try:
                        print(json.dumps(data, ensure_ascii=False), flush=True)
                    except Exception:
                        pass

                def process_data(self, data):
                    raise NotImplementedError('Subclass must implement process_data()')

                def run(self):
                    while True:
                        try:
                            self._load_config()
                            data = self.read_input()
                            if data is not None:
                                result = self.process_data(data)
                                if result is not None:
                                    self.publish(result)
                            else:
                                time.sleep(float(self.config.get('sleep_interval', 0.1)))
                        except KeyboardInterrupt:
                            break
                        except Exception:
                            traceback.print_exc(file=sys.stderr)
                            time.sleep(1)


            if __name__ == '__main__':
                agent = BaseAgent()
                agent.run()
            """;

    /**
     * 初始化模板 — 在内核启动时调用，将 BaseAgent.py 写入 VFS。
     */
    public static void initTemplates() {
        String templatePath = "/factory/templates/BaseAgent.py";
        AiosSdk.getInstance().writeFile("kernel", templatePath, BASE_AGENT_PY);

        log.info("[TemplateManager] BaseAgent.py injected into VFS at {}", templatePath);
        System.out.println("[TemplateManager] BaseAgent.py injected into VFS at " + templatePath);
    }
}
