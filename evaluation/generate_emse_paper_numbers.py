#!/usr/bin/env python3
"""Generate TeX macros and table rows from the frozen JSON artifacts."""

from __future__ import annotations

import json
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evaluation" / "results"
OUT = ROOT / "addtions" / "paper_emse"


def read(path: str):
    return json.loads((RESULTS / path).read_text(encoding="utf-8"))


def wilson(successes: int, trials: int, z: float = 1.959963984540054) -> tuple[float, float]:
    if trials == 0:
        return 0.0, 0.0
    p = successes / trials
    den = 1.0 + z * z / trials
    centre = (p + z * z / (2.0 * trials)) / den
    half = z * math.sqrt((p * (1.0 - p) / trials) + z * z / (4.0 * trials * trials)) / den
    return max(0.0, centre - half), min(1.0, centre + half)


def f3(value: float) -> str:
    return f"{value:.3f}"


def p_display(value: float) -> str:
    """Avoid rendering a small but nonzero p-value as exactly 0.0000."""
    if value >= 0.00005:
        return f"{value:.4f}"
    mantissa, exponent = f"{value:.2e}".split("e")
    return f"{mantissa}\\times 10^{{{int(exponent)}}}"


def pct_pair(successes: int, trials: int) -> str:
    lo, hi = wilson(successes, trials)
    return f"{f3(successes / trials)} [{f3(lo)}, {f3(hi)}]"


def macro(name: str, value: str | int | float) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main() -> int:
    canonical = read("emse_reflexion/canonical_baseline_n100/canonical_manifest.json")["models"]
    autogen = read("emse_autogen_native/pilot_n50_20260809T190905/pilot_summary.json")
    aider = read("emse_aider_native/pilot_gpt_n50_split_20260809T/pilot_summary.json")
    ablation = read("emse_reflexion_ablation/kimi_screen_n20_20260809T/causal_ablation.json")["cells"]
    defense = read("emse_defense_aware/gpt_parallel_n20/paper_draft_forward_defense_bypass.json")
    legal = read("emse_legal_recovery/screen_gpt_n100/legal_recovery.json")
    native_trustorigin = read(
        "emse_reflexion_trustorigin/kimi-k2.6_n50/native_trustorigin.json"
    )
    local_qwen = read(
        "emse_reflexion_ollama_open_anchor/qwen7b_n5/qwen7b_anchor.json"
    )

    by_model = {row["model"]: row for row in canonical}
    ag = {row["model"]: row for row in autogen}
    attack_a = defense["config_A_undefended"]
    attack_b = defense["config_B_defended"]
    trust_raw_attack = native_trustorigin["conditions"]["raw_attack"]
    trust_tagged_attack = native_trustorigin["conditions"]["tagged_attack"]
    trust_raw_benign = native_trustorigin["conditions"]["raw_benign"]
    trust_tagged_benign = native_trustorigin["conditions"]["tagged_benign"]
    qwen_raw_attack = local_qwen["conditions"]["raw_attack"]
    qwen_tagged_attack = local_qwen["conditions"]["tagged_attack"]
    qwen_raw_benign = local_qwen["conditions"]["raw_benign"]
    qwen_tagged_benign = local_qwen["conditions"]["tagged_benign"]
    display = {
        "gpt-5.6-luna": "GPT-5.6 Luna",
        "glm-5.2": "GLM-5.2",
        "kimi-k2.6": "Kimi K2.6",
        "deepseek-v4-flash": "DeepSeek V4 Flash",
        "mimo-v2.5": "MiMo-V2.5",
    }

    macros = [
        "% Generated by evaluation/generate_emse_paper_numbers.py; do not edit by hand.",
        macro("ReflexionModelCount", len(canonical)),
        macro("ReflexionTrialsPerVariantArm", canonical[0]["n_per_variant"]),
        macro("ReflexionBenignTrials", sum(row["benign_total"] for row in canonical)),
        macro("ReflexionGptASR", f3(by_model["gpt-5.6-luna"]["attack_asr"])),
        macro("ReflexionGlmASR", f3(by_model["glm-5.2"]["attack_asr"])),
        macro("ReflexionKimiASR", f3(by_model["kimi-k2.6"]["attack_asr"])),
        macro("ReflexionDeepseekASR", f3(by_model["deepseek-v4-flash"]["attack_asr"])),
        macro("ReflexionMimoASR", f3(by_model["mimo-v2.5"]["attack_asr"])),
        macro("ReflexionMinASR", f3(min(row["attack_asr"] for row in canonical))),
        macro("ReflexionMaxASR", f3(max(row["attack_asr"] for row in canonical))),
        macro("AutoGenTrialsPerVariantArm", autogen[0]["n_per_variant"]),
        macro("AutoGenGlmASR", f3(ag["glm-5.2"]["attack_asr"])),
        macro("AutoGenGptASR", f3(ag["gpt-5.6-luna"]["attack_asr"])),
        macro("AutoGenKimiASR", f3(ag["kimi-k2.6"]["attack_asr"])),
        macro("AutoGenKimiPathRate", f3(ag["kimi-k2.6"]["attack_path_rate"])),
        macro("AiderTrialsPerVariantArm", aider["n_per_variant"]),
        macro("AiderGptASR", f3(aider["attack"]["asr"])),
        macro("AiderGptPathRate", f3(aider["attack"]["native_path_rate"])),
        macro("CausalRawRecoveryASR", f3(ablation["recovery_raw_user_tail"]["attack"]["asr"])),
        macro("CausalTaggedRecoveryASR", f3(ablation["recovery_tagged_user_tail"]["attack"]["asr"])),
        macro("CausalForwardASR", f3(ablation["forward_raw_user_tail"]["attack"]["asr"])),
        macro("CausalSystemTailASR", f3(ablation["recovery_raw_system_tail"]["attack"]["asr"])),
        macro("CausalUserHeadASR", f3(ablation["recovery_raw_user_head"]["attack"]["asr"])),
        macro("DefenseUndefendedASR", f3(attack_a["pooled_asr"])),
        macro("DefenseDefendedASR", f3(attack_b["pooled_asr"])),
        macro("DefenseUndefendedSuccesses", attack_a["total_successes"]),
        macro("DefenseDefendedSuccesses", attack_b["total_successes"]),
        macro("DefenseTrialsPerConfig", attack_a["total_trials"]),
        macro("DefenseUndefendedCILow", f3(attack_a["wilson_95ci"][0])),
        macro("DefenseUndefendedCIHigh", f3(attack_a["wilson_95ci"][1])),
        macro("DefenseDefendedCILow", f3(attack_b["wilson_95ci"][0])),
        macro("DefenseDefendedCIHigh", f3(attack_b["wilson_95ci"][1])),
        macro("DefenseFisherP", f"{defense['fisher_p_A_vs_B']:.4f}"),
        macro("LegalRecoveryRate", f3(legal["recovery_rate"])),
        macro("LegalRecoverySuccesses", legal["recovery_successes"]),
        macro("LegalRecoveryTasks", legal["n_tasks"]),
        macro("LegalFalsePositiveRate", f3(legal["false_positive_rate"])),
        macro("NativeTrustOriginModel", "Kimi K2.6"),
        macro("NativeTrustOriginTrialsPerCell", native_trustorigin["n_per_variant_per_condition"]),
        macro("NativeTrustOriginRawSuccesses", trust_raw_attack["successes"]),
        macro("NativeTrustOriginTaggedSuccesses", trust_tagged_attack["successes"]),
        macro("NativeTrustOriginAttackTrials", trust_raw_attack["trials"]),
        macro("NativeTrustOriginRawASR", f3(trust_raw_attack["rate"])),
        macro("NativeTrustOriginTaggedASR", f3(trust_tagged_attack["rate"])),
        macro("NativeTrustOriginRawCILow", f3(trust_raw_attack["wilson_95ci"][0])),
        macro("NativeTrustOriginRawCIHigh", f3(trust_raw_attack["wilson_95ci"][1])),
        macro("NativeTrustOriginTaggedCILow", f3(trust_tagged_attack["wilson_95ci"][0])),
        macro("NativeTrustOriginTaggedCIHigh", f3(trust_tagged_attack["wilson_95ci"][1])),
        macro("NativeTrustOriginRawFPR", f3(trust_raw_benign["rate"])),
        macro("NativeTrustOriginTaggedFPR", f3(trust_tagged_benign["rate"])),
        macro("NativeTrustOriginFisherP", p_display(native_trustorigin["raw_vs_tagged_attack_fisher_p"])),
        macro("QwenLocalModel", "Qwen2-family qwen:7b"),
        macro("QwenLocalTrialsPerCell", local_qwen["n_per_variant_per_condition"]),
        macro("QwenLocalRawSuccesses", qwen_raw_attack["successes"]),
        macro("QwenLocalTaggedSuccesses", qwen_tagged_attack["successes"]),
        macro("QwenLocalAttackTrials", qwen_raw_attack["trials"]),
        macro("QwenLocalRawASR", f3(qwen_raw_attack["rate"])),
        macro("QwenLocalTaggedASR", f3(qwen_tagged_attack["rate"])),
        macro("QwenLocalRawFPR", f3(qwen_raw_benign["rate"])),
        macro("QwenLocalTaggedFPR", f3(qwen_tagged_benign["rate"])),
        macro("QwenLocalFisherP", p_display(local_qwen["raw_vs_tagged_attack_fisher_p"])),
    ]
    (OUT / "generated_results.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")

    reflexion_rows = []
    for idx, row in enumerate(canonical):
        lo, hi = wilson(row["attack_successes"], row["attack_total"])
        line = f"{display.get(row['model'], row['model'])} & {row['attack_successes']} & {row['attack_total']} & {f3(row['attack_asr'])} & {f3(row['benign_fpr'])} & [{f3(lo)}, {f3(hi)}]"
        reflexion_rows.append(line + (" " + r"\\" if idx < len(canonical) - 1 else ""))
    (OUT / "generated_reflexion_rows.tex").write_text("\n".join(reflexion_rows) + "\n", encoding="utf-8")

    native_rows = []
    native_specs = [
        f"AutoGen & {display.get(row['model'], row['model'])} & {row['attack_successes']}/{row['attack_total']} ({f3(row['attack_asr'])}) & {f3(row['attack_path_rate'])} & {f3(row['benign_fpr'])}"
        for row in autogen
    ]
    native_specs.append(
        f"Aider & GPT-5.6 Luna & {aider['attack']['successes']}/{aider['attack']['trials']} ({f3(aider['attack']['asr'])}) & {f3(aider['attack']['native_path_rate'])} & {f3(aider['benign']['asr'])}"
    )
    native_rows = [line + (" " + r"\\" if idx < len(native_specs) - 1 else "") for idx, line in enumerate(native_specs)]
    (OUT / "generated_native_rows.tex").write_text("\n".join(native_rows) + "\n", encoding="utf-8")

    trust_rows = [
        f"{display.get(native_trustorigin['model'], native_trustorigin['model'])} & Raw & {trust_raw_attack['successes']}/{trust_raw_attack['trials']} ({f3(trust_raw_attack['rate'])}) & {f3(trust_raw_benign['rate'])} & [{f3(trust_raw_attack['wilson_95ci'][0])}, {f3(trust_raw_attack['wilson_95ci'][1])}] \\\\",
        f"{display.get(native_trustorigin['model'], native_trustorigin['model'])} & TrustOrigin & {trust_tagged_attack['successes']}/{trust_tagged_attack['trials']} ({f3(trust_tagged_attack['rate'])}) & {f3(trust_tagged_benign['rate'])} & [{f3(trust_tagged_attack['wilson_95ci'][0])}, {f3(trust_tagged_attack['wilson_95ci'][1])}] \\\\",
    ]
    (OUT / "generated_trustorigin_rows.tex").write_text("\n".join(trust_rows) + "\n", encoding="utf-8")

    ablation_rows = []
    for key, cell in ablation.items():
        factors = cell["factors"]
        ablation_rows.append(
            f"{factors['channel']} / {factors['provenance']} / {factors['role']} / {factors['position']} & {cell['attack']['successes']}/{cell['attack']['trials']} ({f3(cell['attack']['asr'])}) & {f3(cell['benign']['asr'])} \\\\"
        )
    (OUT / "generated_ablation_rows.tex").write_text("\n".join(ablation_rows) + "\n", encoding="utf-8")

    print(OUT / "generated_results.tex")
    print(OUT / "generated_reflexion_rows.tex")
    print(OUT / "generated_native_rows.tex")
    print(OUT / "generated_ablation_rows.tex")
    print(OUT / "generated_trustorigin_rows.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
