#!/usr/bin/env python3
"""Summarize the Java mixed benign/attack QoS matrix."""

from __future__ import annotations

import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path


def percentile(values: list[float], q: float) -> float:
    values = sorted(values)
    if not values:
        return math.nan
    pos = q * (len(values) - 1)
    lo, hi = math.floor(pos), math.ceil(pos)
    return values[lo] if lo == hi else values[lo] * (hi - pos) + values[hi] * (pos - lo)


def write_csv(path: Path, records: list[dict]) -> None:
    if not records:
        return
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(records[0]))
        writer.writeheader()
        writer.writerows(records)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input-dir", type=Path,
                        default=Path(__file__).resolve().parents[1] / "evaluation/target/jvm_starvation_new")
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    out = args.output_dir or args.input_dir
    out.mkdir(parents=True, exist_ok=True)

    rows: list[dict] = []
    for path in sorted(args.input_dir.glob("jvm_permission_starvation_*qos*.raw.jsonl")):
        rows.extend(json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip())
    if not rows:
        raise SystemExit("no qos raw JSONL files found")

    grouped: dict[tuple, list[dict]] = defaultdict(list)
    for row in rows:
        grouped[(row["host_id"], row["run_id"], row["architecture"], int(row["qos_benign_percent"]))].append(row)

    records: list[dict] = []
    for (host, run_id, architecture, benign_percent), group in sorted(grouped.items(), key=lambda x: str(x[0])):
        benign = [r for r in group if r["workload_class"] == "benign"]
        attack = [r for r in group if r["workload_class"] == "attack"]
        records.append({
            "host_id": host,
            "run_id": run_id,
            "architecture": architecture,
            "benign_percent": benign_percent,
            "n": len(group),
            "benign_n": len(benign),
            "attack_n": len(attack),
            "benign_completion_rate": sum(bool(r["benign_completed"]) for r in benign) / len(benign) if benign else math.nan,
            "benign_error_tightening_rate": sum(bool(r["error_tightening"]) for r in benign) / len(benign) if benign else math.nan,
            "attack_secure_rate": sum(bool(r["secure_decision"]) for r in attack) / len(attack) if attack else math.nan,
            "attack_timeout_rate": sum(bool(r["timed_out"]) for r in attack) / len(attack) if attack else math.nan,
            "latency_p50_ms": percentile([float(r["latency_ms"]) for r in group], .50),
            "latency_p95_ms": percentile([float(r["latency_ms"]) for r in group], .95),
        })
    write_csv(out / "computing_qos_summary.csv", records)

    def macro_token(value: object) -> str:
        return "".join(ch for ch in str(value) if ch.isalnum())

    macros = [
        "% Generated by evaluation/analyze_qos_experiments.py; do not edit.",
        f"\\newcommand{{\\ComputingQosObservationCount}}{{{len(rows)}}}",
        f"\\newcommand{{\\ComputingQosConfigCount}}{{{len(records)}}}",
    ]
    for record in records:
        host = macro_token(record["host_id"])
        arch = macro_token(record["architecture"])
        mix = record["benign_percent"]
        mix_word = {100: "onehundred", 90: "ninety", 75: "seventyfive", 50: "fifty"}[mix]
        stem = f"\\ComputingQos{host}{arch}B{mix_word}"
        macros.extend([
            f"\\newcommand{{{stem}BenignCompletion}}{{{100 * record['benign_completion_rate']:.1f}\\%}}",
            f"\\newcommand{{{stem}BenignTightening}}{{{100 * record['benign_error_tightening_rate']:.1f}\\%}}",
            f"\\newcommand{{{stem}AttackSecure}}{{{100 * record['attack_secure_rate']:.1f}\\%}}",
            f"\\newcommand{{{stem}AttackTimeout}}{{{100 * record['attack_timeout_rate']:.1f}\\%}}",
            f"\\newcommand{{{stem}PNinetyFive}}{{{record['latency_p95_ms']:.3f}}}",
        ])
        if record["host_id"] == "windows-local" and record["benign_percent"] in (50, 90):
            short_arch = {
                "LAYER_SEPARATED_FAIL_OPEN": "FailOpen",
                "LAYER_SEPARATED_FAIL_CLOSED": "FailClosed",
                "ISOLATED_NO_COUPLING": "Isolated",
                "NEURON_COUPLED": "Coupled",
            }[record["architecture"]]
            mix_word = {90: "ninety", 50: "fifty"}[record["benign_percent"]]
            clean = f"\\ComputingQos{short_arch}B{mix_word}"
            macros.extend([
                f"\\newcommand{{{clean}BenignCompletion}}{{{100 * record['benign_completion_rate']:.1f}\\%}}",
                f"\\newcommand{{{clean}BenignTightening}}{{{100 * record['benign_error_tightening_rate']:.1f}\\%}}",
                f"\\newcommand{{{clean}AttackSecure}}{{{100 * record['attack_secure_rate']:.1f}\\%}}",
                f"\\newcommand{{{clean}AttackTimeout}}{{{100 * record['attack_timeout_rate']:.1f}\\%}}",
            ])
    paper_generated = Path(__file__).resolve().parents[1] / "addtions/paper/generated"
    paper_generated.mkdir(parents=True, exist_ok=True)
    (paper_generated / "qos_results.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print(f"loaded {len(rows)} QoS observations from {len(records)} cells")


if __name__ == "__main__":
    main()
