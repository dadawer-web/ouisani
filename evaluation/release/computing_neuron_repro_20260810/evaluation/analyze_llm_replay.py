#!/usr/bin/env python3
"""Generate paper macros from the fixed-trace Java LLM replay summary."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path


def pct(value: str) -> str:
    return f"{100.0 * float(value):.1f}\\%"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--summary",
        type=Path,
        default=Path(__file__).resolve().parents[0]
        / "target/computing_llm_replay_v3/llm_trace_replay_summary.csv",
    )
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    output_dir = args.output_dir or Path(__file__).resolve().parents[1] / "addtions/paper/generated"
    output_dir.mkdir(parents=True, exist_ok=True)

    with args.summary.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        raise SystemExit(f"empty replay summary: {args.summary}")

    sessions = sum(int(row["n_sessions"]) for row in rows if row["architecture"] == "NEURON_COUPLED")
    trace_calls = sum(int(row["n_calls"]) for row in rows if row["architecture"] == "NEURON_COUPLED")
    evaluated_calls = trace_calls * len({row["architecture"] for row in rows})
    by_class = {
        workload: next(row for row in rows if row["architecture"] == "NEURON_COUPLED" and row["workload_class"] == workload)
        for workload in ("benign", "attack")
    }

    def completion(architecture: str, workload: str) -> str:
        row = next(row for row in rows if row["architecture"] == architecture and row["workload_class"] == workload)
        return pct(row["session_completion_rate"])

    def timeout(architecture: str, workload: str) -> str:
        row = next(row for row in rows if row["architecture"] == architecture and row["workload_class"] == workload)
        return pct(row["timeout_rate"])

    macros = [
        "% Generated by evaluation/analyze_llm_replay.py; do not edit.",
        f"\\newcommand{{\\LlmReplaySessions}}{{{sessions}}}",
        f"\\newcommand{{\\LlmReplayTraceCalls}}{{{trace_calls}}}",
        f"\\newcommand{{\\LlmReplayCalls}}{{{evaluated_calls}}}",
        f"\\newcommand{{\\LlmReplayBenignSessions}}{{{by_class['benign']['n_sessions']}}}",
        f"\\newcommand{{\\LlmReplayAttackSessions}}{{{by_class['attack']['n_sessions']}}}",
        f"\\newcommand{{\\LlmReplayBenignCalls}}{{{by_class['benign']['n_calls']}}}",
        f"\\newcommand{{\\LlmReplayAttackCalls}}{{{by_class['attack']['n_calls']}}}",
    ]
    for arch, short in (
        ("LAYER_SEPARATED_FAIL_OPEN", "FailOpen"),
        ("LAYER_SEPARATED_FAIL_CLOSED", "FailClosed"),
        ("ISOLATED_NO_COUPLING", "Isolated"),
        ("NEURON_COUPLED", "Coupled"),
    ):
        for workload, label in (("benign", "Benign"), ("attack", "Attack")):
            macros.append(f"\\newcommand{{\\LlmReplay{short}{label}Completion}}{{{completion(arch, workload)}}}")
            macros.append(f"\\newcommand{{\\LlmReplay{short}{label}Timeout}}{{{timeout(arch, workload)}}}")
    (output_dir / "llm_replay_results.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print(f"wrote {output_dir / 'llm_replay_results.tex'} for {sessions} sessions and {evaluated_calls} evaluated calls")


if __name__ == "__main__":
    main()
