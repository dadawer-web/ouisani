#!/usr/bin/env python3
"""Summarize the JVM response surface for the CCPE concurrency narrative.

The analysis treats an independently started JVM as the replication unit and
adds executor-oriented observables: offered request rate, estimated worker
demand, permission-queue depth, timeout rate, and p95 decision latency.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path


ARCH_SHORT = {
    "LAYER_SEPARATED_FAIL_OPEN": "FailOpen",
    "LAYER_SEPARATED_FAIL_CLOSED": "FailClosed",
    "ISOLATED_NO_COUPLING": "Isolated",
    "NEURON_COUPLED": "Coupled",
}

LEVELS = {
    "low": (1, 100, 0.5),
    "medium": (4, 500, 2.0),
    "high": (16, 2000, 5.0),
}


def percentile(values: list[float], q: float) -> float:
    xs = sorted(values)
    if not xs:
        return math.nan
    pos = q * (len(xs) - 1)
    lo, hi = math.floor(pos), math.ceil(pos)
    return xs[lo] if lo == hi else xs[lo] * (hi - pos) + xs[hi] * (pos - lo)


def token(value: object) -> str:
    # TeX control-sequence names are letter-only; strip run-number digits.
    return "".join(ch for ch in str(value) if ch.isalpha())


def read_rows(input_dir: Path) -> list[dict]:
    rows: list[dict] = []
    for path in sorted(input_dir.glob("jvm_permission_starvation_*.raw.jsonl")):
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                row = json.loads(line)
                row.setdefault("run_id", path.stem.replace("jvm_permission_starvation_", ""))
                # The historical smoke file predates explicit host metadata;
                # it was collected on the local Windows host.
                row.setdefault("host_id", "windows-local")
                rows.append(row)
    if not rows:
        raise SystemExit(f"no raw JVM JSONL files found in {input_dir}")
    return rows


def summarize(rows: list[dict]) -> dict:
    n = len(rows)
    timeouts = sum(bool(row.get("timed_out")) for row in rows)
    secure = sum(bool(row.get("secure_decision")) for row in rows)
    latencies = [float(row["latency_ms"]) for row in rows]
    queues = [float(row.get("permission_queue_depth", 0)) for row in rows]
    first = rows[0]
    attackers = int(first["attackers"])
    qps = int(first["qps_per_attacker"])
    hold = float(first["lock_hold_ms"])
    offered = attackers * qps
    worker_demand = offered * hold / 10.0
    return {
        "host_id": first["host_id"],
        "architecture": first["architecture"],
        "level": next(name for name, factors in LEVELS.items()
                       if (attackers, qps, hold) == factors),
        "attackers": attackers,
        "qps_per_attacker": qps,
        "lock_hold_ms": hold,
        "offered_qps": offered,
        "estimated_worker_demand_pct": worker_demand,
        "n": n,
        "run_count": len({row.get("run_id") for row in rows}),
        "timeout_rate": timeouts / n if n else math.nan,
        "secure_rate": secure / n if n else math.nan,
        "latency_p50_ms": percentile(latencies, 0.50),
        "latency_p95_ms": percentile(latencies, 0.95),
        "queue_mean": sum(queues) / n if n else math.nan,
        "queue_p95": percentile(queues, 0.95),
        "resource_rejections_mean": sum(int(row.get("resource_rejections", 0)) for row in rows) / n if n else math.nan,
    }


def write_csv(path: Path, records: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(records[0]))
        writer.writeheader()
        writer.writerows(records)


def write_macros(path: Path, records: list[dict], total_rows: int, run_count: int,
                 additional_rows: int, pressure_rows: int, additional_runs: int) -> None:
    lines = [
        "% Generated by evaluation/analyze_ccpe_concurrency.py; do not edit.",
        f"\\newcommand{{\\CCPEConcurrencyObservationCount}}{{{total_rows:,}}}",
        f"\\newcommand{{\\CCPEConcurrencyRunCount}}{{{run_count}}}",
        f"\\newcommand{{\\CCPEAdditionalObservationCount}}{{{additional_rows:,}}}",
        f"\\newcommand{{\\CCPEPressureSurfaceObservationCount}}{{{pressure_rows:,}}}",
        f"\\newcommand{{\\CCPEAdditionalRunCount}}{{{additional_runs}}}",
    ]
    for record in records:
        prefix = "\\CCPE" + token(record["host_id"]) + token(record["level"]) + ARCH_SHORT[record["architecture"]]
        lines.extend([
            f"\\newcommand{{{prefix}Timeout}}{{{100 * record['timeout_rate']:.1f}\\%}}",
            f"\\newcommand{{{prefix}Secure}}{{{100 * record['secure_rate']:.1f}\\%}}",
            f"\\newcommand{{{prefix}LatencyPninetyfive}}{{{record['latency_p95_ms']:.2f}}}",
            f"\\newcommand{{{prefix}QueuePninetyfive}}{{{record['queue_p95']:.1f}}}",
        ])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument("--input-dir", type=Path, default=root / "evaluation/target/jvm_starvation_new")
    parser.add_argument("--output-dir", type=Path, default=root / "evaluation/target/ccpe_concurrency")
    parser.add_argument("--paper-generated", type=Path,
                        default=root / "addtions/paper_ccpe/generated/ccpe_concurrency_results.tex")
    args = parser.parse_args()

    all_rows = read_rows(args.input_dir)
    rows = [row for row in all_rows
            if row.get("experiment") == "pressure_surface"
            and int(row.get("deadline_ms", 0)) == 10
            and row.get("split") == "test"]
    selected: list[dict] = []
    for host in sorted({row["host_id"] for row in rows}):
        for level, factors in LEVELS.items():
            for architecture in ARCH_SHORT:
                cell = [row for row in rows
                        if row["host_id"] == host
                        and row["architecture"] == architecture
                        and (int(row["attackers"]), int(row["qps_per_attacker"]), float(row["lock_hold_ms"])) == factors]
                if cell:
                    selected.append(summarize(cell))
    if not selected:
        raise SystemExit("no selected CCPE pressure cells found")

    args.output_dir.mkdir(parents=True, exist_ok=True)
    write_csv(args.output_dir / "ccpe_concurrency_surface.csv", selected)
    manifest = {
        "input_dir": str(args.input_dir),
        "experiment": "pressure_surface",
        "deadline_ms": 10,
        "levels": LEVELS,
        "observations": len(rows),
        "runs": sorted({row.get("run_id") for row in rows}),
        "hosts": sorted({row.get("host_id") for row in rows}),
    }
    (args.output_dir / "ccpe_concurrency_manifest.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8")
    additional_all = [row for row in all_rows if row.get("run_id") == "ccpe_core_01"]
    additional = [row for row in rows
                  if row.get("host_id") == "windows-ccpe-core-01"
                  and row.get("run_id") == "ccpe_core_01"]
    write_macros(args.paper_generated, selected, len(rows), len(manifest["runs"]),
                 len(additional_all), len(additional),
                 len({row.get("run_id") for row in additional_all}))
    print(f"loaded {len(rows):,} pressure-surface observations from {len(manifest['runs'])} runs")
    print(f"wrote {args.output_dir / 'ccpe_concurrency_surface.csv'}")
    print(f"wrote {args.paper_generated}")


if __name__ == "__main__":
    main()
